def rows():
    for t, cat, city, area, who, cost, tags, lat, lng, desc in ROWS:
        yield dict(title=t, category=cat, city=city, area=area, for_who=who,
                   cost_hint=cost, tags=tags, lat=lat, lng=lng, description=desc, url=None)


def q(v):
    return "null" if v is None else f"$q${v}$q$"


def sql():
    out = ["-- Generated by scripts/suggestions_batch3.py",
           "insert into public.suggestions (title,category,city,area,description,cost_hint,tags,lat,lng,for_who) values"]
    vals = []
    for r in rows():
        tags = "array[" + ",".join(q(t) for t in r["tags"]) + "]::text[]"
        vals.append(f"({q(r['title'])},{q(r['category'])},{q(r['city'])},{q(r['area'])},{q(r['description'])},"
                    f"{q(r['cost_hint'])},{tags},{r['lat']},{r['lng']},{q(r['for_who'])})")
    return "\n".join(out) + "\n" + ",\n".join(vals) + ";\n"


if sys.argv[1:] == ["sql"]:
    sys.stdout.write(sql())
else:
    json.dump(list(rows()), sys.stdout, ensure_ascii=False, indent=2)
